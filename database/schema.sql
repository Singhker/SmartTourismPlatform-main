    female_visitors INTEGER,
    children_visitors INTEGER,
    senior_citizen_visitors INTEGER,
    student_visitors INTEGER,
    group_visitors INTEGER,
    solo_visitors INTEGER,
    average_visit_duration_hours REAL,
    average_spending_inr REAL,
    weather_condition TEXT,
    special_event TEXT,
    festival_season TEXT,
    visitor_satisfaction REAL,
    revenue_inr REAL,
    growth_percentage REAL,
    remarks TEXT,
    created_date TEXT,
    updated_date TEXT,

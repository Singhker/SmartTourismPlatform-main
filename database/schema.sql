-- Tourist Places Table
CREATE TABLE IF NOT EXISTS tourist_places (
    place_id TEXT PRIMARY KEY,
    place_name TEXT NOT NULL,
    district TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    latitude REAL,
    longitude REAL,
    address TEXT,
    entry_fee_inr REAL,
    opening_time TEXT,
    closing_time TEXT,
    best_season TEXT,
    visit_duration_hours REAL,
    popularity_level TEXT,
    family_friendly TEXT,
    adventure_level TEXT,
    accessibility TEXT,
    parking_available TEXT,
    washroom_available TEXT,
    wheelchair_accessible TEXT,
    official_website TEXT,
    image_url TEXT,
    status TEXT,
    created_date TEXT,
    updated_date TEXT
);


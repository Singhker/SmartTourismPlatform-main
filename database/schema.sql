-- Weather Table
CREATE TABLE IF NOT EXISTS weather (
    weather_id TEXT PRIMARY KEY,
    place_id TEXT,
    year INTEGER,
    month_number INTEGER,
    month_name TEXT,
    season TEXT,
    average_temperature_c REAL,
    minimum_temperature_c REAL,
    maximum_temperature_c REAL,
    humidity_percentage INTEGER,
    rainfall_mm REAL,
    wind_speed_kmph REAL,
    weather_condition TEXT,
    air_quality_index INTEGER,
    uv_index INTEGER,
    visibility_km REAL,
    sunrise_time TEXT,
    sunset_time TEXT,
    tourism_suitability TEXT,
    weather_warning TEXT,
    created_date TEXT,
    updated_date TEXT,
    FOREIGN KEY (place_id) REFERENCES tourist_places(place_id)
);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_visitor_place_year ON visitor_statistics(place_id, year);
CREATE INDEX IF NOT EXISTS idx_reviews_place ON reviews(place_id);
CREATE INDEX IF NOT EXISTS idx_hotels_place ON hotels(place_id);
CREATE INDEX IF NOT EXISTS idx_restaurants_place ON restaurants(place_id);
CREATE INDEX IF NOT EXISTS idx_events_place ON events(place_id);
CREATE INDEX IF NOT EXISTS idx_weather_place ON weather(place_id, year, month_number);